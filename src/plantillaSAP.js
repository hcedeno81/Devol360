export const PLANTILLA_SAP_BASE64 = PARTES.join("");

// Convierte el base64 en el ArrayBuffer que espera JSZip.
export function plantillaSAPEmbebida() {
  const bin = atob(PLANTILLA_SAP_BASE64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes.buffer;
}
